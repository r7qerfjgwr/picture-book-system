-- 生成阅读记录
INSERT INTO reading_log (child_id, book_id, start_time, end_time, duration, page_turn_count, completion_rate, is_completed, focus_score)
SELECT
    c.id as child_id,
    FLOOR(1 + RAND() * 100) as book_id,
    DATE_SUB(NOW(), INTERVAL FLOOR(RAND() * 30) DAY) as start_time,
    DATE_SUB(NOW(), INTERVAL FLOOR(RAND() * 30) DAY) as end_time,
    FLOOR(5 + RAND() * 25) as duration,
    FLOOR(5 + RAND() * 20) as page_turn_count,
    FLOOR(50 + RAND() * 50) as completion_rate,
    IF(RAND() > 0.3, 1, 0) as is_completed,
    ROUND(50 + RAND() * 50, 2) as focus_score
FROM child c
CROSS JOIN (SELECT 1 as n UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5
            UNION SELECT 6 UNION SELECT 7 UNION SELECT 8 UNION SELECT 9 UNION SELECT 10) n;

-- 更新绘本阅读次数
UPDATE book b SET read_count = (SELECT COUNT(*) FROM reading_log WHERE book_id = b.id);

